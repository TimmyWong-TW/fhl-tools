// Writes the tool reference (every tool and parameter) into README.md and README.zh-TW.md between
// <!-- tools:start --> and <!-- tools:end -->, from the tool definitions in src/tools.ts.
// `pnpm readme` updates; `pnpm readme --check` fails if they are out of date (part of `pnpm check`).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { TOOLS, type ToolDef } from "../src/tools";

const here = (p: string) => fileURLToPath(import.meta.url + "/../" + p);
const check = process.argv.includes("--check");

const L = {
  en: { param: "Parameter", type: "Type", req: "Required", desc: "Description", def: "default", none: "No parameters.", example: "Example", local: "local server only", yes: "yes" },
  zh: { param: "參數", type: "型別", req: "必填", desc: "說明", def: "預設", none: "無參數。", example: "範例", local: "僅本機版", yes: "是" },
};

const cell = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function typeOf(p: any): string {
  if (p.enum) return p.enum.map((x: string) => `\`${x}\``).join(" \\| ");
  if (p.type === "array") {
    const items: string[] = p.items?.enum ? p.items.enum.map((x: string) => `\`${x}\``) : ([] as string[]).concat(p.items?.type ?? "any");
    return items.length > 1 ? `(${items.join(" \\| ")})[]` : `${items[0]}[]`;
  }
  return ([] as string[]).concat(p.type ?? "any").join(" \\| ");
}

function section(t: ToolDef, l: typeof L.en): string {
  const req = new Set(t.inputSchema.required ?? []);
  const props = Object.entries(t.inputSchema.properties);
  const head = `### \`${t.name}\` ${t.title}${t.restricted ? ` _(${l.local})_` : ""}\n\n${t.description}\n`;
  const table = props.length
    ? `\n| ${l.param} | ${l.type} | ${l.req} | ${l.desc} |\n| --- | --- | --- | --- |\n` +
      props
        .map(([k, p]: [string, any]) => `| \`${k}\` | ${typeOf(p)} | ${req.has(k) ? l.yes : ""} | ${cell(p.description)}${p.default !== undefined ? ` (${l.def} \`${JSON.stringify(p.default)}\`)` : ""} |`)
        .join("\n") +
      "\n"
    : `\n${l.none}\n`;
  return `${head}${table}\n${l.example}: \`${JSON.stringify(t.example)}\`\n`;
}

let stale = false;
for (const [file, l] of [["../README.md", L.en], ["../README.zh-TW.md", L.zh]] as const) {
  const path = here(file);
  const text = readFileSync(path, "utf8");
  const block = `<!-- tools:start -->\n<!-- Generated by scripts/readme.ts from src/tools.ts; do not edit by hand. -->\n\n${TOOLS.map((t) => section(t, l)).join("\n")}\n<!-- tools:end -->`;
  const next = text.replace(/<!-- tools:start -->[\s\S]*?<!-- tools:end -->/, block);
  if (!/<!-- tools:start -->/.test(text)) throw new Error(`${file}: missing <!-- tools:start --> marker`);
  if (next !== text) {
    stale = true;
    if (!check) writeFileSync(path, next);
  }
  console.log(`${file}: ${next === text ? "up to date" : check ? "OUT OF DATE" : "updated"}`);
}
if (check && stale) {
  console.error("Tool reference in README is out of date: run `pnpm readme`.");
  process.exit(1);
}
