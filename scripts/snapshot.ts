// Refreshes src/snapshot.ts: the docs page plus a book table (bid <-> names) derived from responses.
// Build input for `pnpm build:spec` and the test fixture.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DOCS_URL, UPSTREAM_BASE } from "../src/scaffold";
import type { Book, Version } from "../src/types";

const here = (p: string) => fileURLToPath(import.meta.url + "/../" + p);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

const res = await fetch(DOCS_URL);
if (!res.ok) throw new Error(`HTTP ${res.status}`);
const html = await res.text();

// Canon 1-66 from listall.html: id,engs,engf,chineses,chinesef,engs_short
const csv = await (await fetch(UPSTREAM_BASE + "listall.html")).text();
const books: Book[] = csv
  .split(/\r?\n/)
  .map((l) => l.split(",").map((c) => c.trim()))
  .filter((r) => r.length >= 5 && /^\d+$/.test(r[0]))
  .map(([bid, engs, engf, chineses, chinesef, short]) => ({ bid: +bid, engs, engf, chineses, chinesef, aliases: short && short !== engs ? [short] : [] }));

// Apocrypha (qsub, 101-115) and Apostolic Fathers (qaf, 201-217): read names back from responses.
for (const [file, from, to] of [["qsub.php", 101, 115], ["qaf.php", 201, 217]] as const) {
  for (let bid = from; bid <= to; bid++) {
    await sleep(400);
    const j: any = await (await fetch(`${UPSTREAM_BASE}${file}?bid=${bid}&chap=1&sec=1`)).json();
    const r = j.record?.[0];
    if (r?.bid === bid) books.push({ bid, engs: r.engs, chineses: r.chineses, aliases: [] });
    else console.warn(`${file} bid=${bid}: no record`);
  }
}

// Bible text versions (code <-> name) for validating/translating `version` on qb/qsb/se.
const ab: any = await (await fetch(UPSTREAM_BASE + "ab.php")).json();
const versions: Version[] = ab.record.map((r: any) => ({ code: r.book, name: r.cname, strong: r.strong === 1, ntonly: r.ntonly === 1, otonly: r.otonly === 1 }));

const snap = {
  html,
  etag: res.headers.get("etag") ?? undefined,
  lastModified: res.headers.get("last-modified") ?? undefined,
  fetchedAt: new Date().toISOString(),
  books,
  versions,
};
writeFileSync(
  here("../src/snapshot.ts"),
  `// Generated by scripts/snapshot.ts - do not edit.\nimport type { Snapshot } from "./types";\n\nexport const SNAPSHOT: Snapshot = ${JSON.stringify(snap, null, 2)};\n`,
);
console.log(`snapshot: ${html.length} chars, etag ${snap.etag}, last-modified ${snap.lastModified}, ${books.length} books, ${versions.length} versions`);
